#!/usr/bin/env python3
"""Generate the 256-character 8x16 VGA ROM from the vendored public-domain font.

Usage: python3 scripts/font2mem.py [font8x8_basic.h] [font_rom.mem] [--check]
No network or third-party package is needed. Each source row is doubled and
its bits reversed: bit 7 in the output is the leftmost pixel. Codes 128..255
are blank. --check verifies the checked-in image without rewriting it.
"""
from __future__ import annotations

import argparse
import hashlib
from pathlib import Path
import re
import sys

REPO = Path(__file__).resolve().parent.parent
SOURCE = REPO / "rtl/mem/fonts/font8x8_basic.h"
TARGET = REPO / "rtl/mem/font_rom.mem"


def parse_font(text: str) -> list[list[int]]:
    """Parse this small C initializer as data; never eval or execute the input."""
    text = re.sub(r"/\*.*?\*/|//[^\r\n]*", "", text, flags=re.S)
    array = re.search(r"\bfont8x8_basic\s*\[128\]\s*\[8\]\s*=\s*\{(.*?)\}\s*;", text, re.S)
    if array is None:
        raise ValueError("expected font8x8_basic[128][8] initializer")
    body = array.group(1)
    rows = re.findall(r"\{([^{}]*)\}", body)
    if len(rows) != 128 or re.sub(r"\{[^{}]*\}|[\s,]", "", body):
        raise ValueError("font must contain exactly 128 glyphs")
    result = []
    for row in rows:
        tokens = [value.strip() for value in row.split(",")]
        if tokens[-1:] == [""]:
            tokens.pop()
        if len(tokens) != 8 or any(re.fullmatch(r"0[xX][0-9a-fA-F]{2}", value) is None for value in tokens):
            raise ValueError("each glyph must contain exactly eight hexadecimal bytes")
        result.append([int(value, 16) for value in tokens])
    return result


def convert(data: bytes) -> str:
    glyphs = parse_font(data.decode("ascii"))
    lines = ["// Generated by scripts/font2mem.py; 256 x 16 rows, MSB at left.",
             "// Source SHA-256: " + hashlib.sha256(data).hexdigest()]
    for code in range(256):
        for row in (glyphs[code] if code < 128 else [0] * 8):
            value = int(f"{row:08b}"[::-1], 2)
            lines.extend([f"{value:02x}"] * 2)
    return "\n".join(lines) + "\n"


def c_header(data: bytes) -> str:
    glyphs = parse_font(data.decode("ascii"))
    lines = ["/* Generated by font2mem.py from the pinned public-domain font.",
             " * Source bytes are LSB at left; used by pixel-mode C text. */",
             "static const uint8_t rvc_font8x8[128][8] = {"]
    lines += ["    {" + ",".join(f"0x{x:02x}" for x in glyph) + "}," for glyph in glyphs]
    return "\n".join(lines + ["};", ""])


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("source", type=Path, nargs="?", default=SOURCE)
    parser.add_argument("target", type=Path, nargs="?", default=TARGET)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--c-header", type=Path, help="also generate/check pixel-text C font")
    args = parser.parse_args()
    try:
        source = args.source.read_bytes()
        image = convert(source).encode("ascii")
        if args.check:
            if args.target.read_bytes() != image:
                raise ValueError("font ROM differs; regenerate with scripts/font2mem.py")
        else:
            args.target.parent.mkdir(parents=True, exist_ok=True)
            args.target.write_bytes(image)
        if args.c_header:
            header = c_header(source).encode("ascii")
            if args.check:
                if args.c_header.read_bytes() != header:
                    raise ValueError("pixel-text C font differs; regenerate --c-header")
            else:
                args.c_header.parent.mkdir(parents=True, exist_ok=True)
                args.c_header.write_bytes(header)
    except (OSError, UnicodeError, ValueError) as exc:
        print(f"font2mem: {exc}", file=sys.stderr)
        return 1
    print(f"{'Verified' if args.check else 'Generated'} 4096 font bytes: {args.target}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
