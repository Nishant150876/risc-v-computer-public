#!/usr/bin/env python3
"""Generate the debug-protocol C header and golden vectors from protocol/schema.json.

    python3 scripts/gen_protocol.py           write the generated files
    python3 scripts/gen_protocol.py --check   fail if any generated file is out of date

Outputs:
    firmware/tab5/components/dbglink/include/dbglink_schema.h
    protocol/vectors/frames.txt     framing and receive-error vectors
    protocol/vectors/sessions.txt   device session/replay scenarios (from host/dbglink/device.py)
"""
import argparse
import random
import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO / "host"))
from dbglink import (CHANNEL, KIND, LIMITS, OPCODE, SCHEMA, DebugDevice, Frame, FrameError,  # noqa: E402
                     StreamDecoder, cobs_encode, crc32, encode_frame, wire_frame)

HEADER_OUT = REPO / "firmware/tab5/components/dbglink/include/dbglink_schema.h"
RTL_OUT = REPO / "rtl/debug/dbg_pkg.sv"
FRAMES_OUT = REPO / "protocol/vectors/frames.txt"
SESSIONS_OUT = REPO / "protocol/vectors/sessions.txt"
C_TYPE = {"u8": "uint8_t", "u16": "uint16_t", "u32": "uint32_t", "u64": "uint64_t"}
C_SIZE = {"u8": 1, "u16": 2, "u32": 4, "u64": 8}


def sv_package():
    """RTL constants and wire types come from the same schema as C/Python."""
    out = ["`timescale 1ns/1ps",
           "// Generated by scripts/gen_protocol.py; change protocol/schema.json.",
           "package dbg_pkg;",
           f"    typedef enum logic [7:0] {{ DBG_PROTOCOL_VERSION = 8'd{SCHEMA['protocol_version']} }} dbg_version_t;",
           f"    typedef enum logic [7:0] {{ DBG_SCHEMA_MINOR = 8'd{SCHEMA['schema_minor']} }} dbg_minor_t;"]
    for name,value in SCHEMA["limits"].items():
        out.append(f"    typedef enum logic [31:0] {{ DBG_{name.upper()} = 32'd{value} }} dbg_limit_{name}_t;")
    groups = [("channels","CH",8),("kinds","KIND",8),("opcodes","OP",16),
              ("status","ST",16),("frame_errors","ERR",8),("capabilities","CAP",32),
              ("cpu_states","CPU",8),("operation_states","OPST",8),
              ("link_states","LINK",8),("session_states","SESSION",8),
              ("halt_reasons","HALT",8),("isa_flags","ISA",32),("status_valid_bits","VALID",32)]
    for group,prefix,width in groups:
        out.append(f"    typedef enum logic [{width-1}:0] {{")
        constants=[]
        for name,value in SCHEMA[group].items():
            if group in ("capabilities","isa_flags","status_valid_bits"): value=1<<value
            constants.append(f"        DBG_{prefix}_{name} = {width}'d{value}")
        out.append(",\n".join(constants))
        out.append(f"    }} dbg_{group}_t;")
    out += ["""
    typedef struct packed {
        logic [7:0] version, channel, kind, flags;
        logic [15:0] opcode, status;
        logic [31:0] request_id;
        logic [63:0] session_id;
        logic [15:0] length, reserved;
        logic [DBG_MAX_PAYLOAD*8-1:0] payload; // byte zero occupies bits 7:0
    } dbg_frame_t;
    typedef struct packed {
        logic cyc,stb,we,bist,debug_claim,bist_claim;
        logic [29:0] address; // aligned word address, B4 Classic
        logic [31:0] data;
        logic [3:0] select_bytes;
        logic fault_enable;
        logic [31:0] fault_address,fault_mask;
    } dbg_wb_request_t;
    typedef struct packed {
        logic ack,error,debug_grant,bist_grant,cpu_owns;
        logic fault_fired;
        logic [31:0] fault_original,fault_observed;
        logic [31:0] data;
    } dbg_wb_response_t;
    function automatic logic [31:0] dbg_crc_byte(input logic [31:0] state,
                                                input logic [7:0] value);
        logic [31:0] crc;
        crc = state ^ {24'd0,value};
        for (int bit_index=0; bit_index<8; bit_index=bit_index+1)
            crc = crc[0] ? (crc >> 1)^32'hedb88320 : crc >> 1;
        return crc;
    endfunction
    function automatic logic [7:0] dbg_header_byte(input dbg_frame_t frame,input int index);
        case (index)
            0: return frame.version; 1: return frame.channel;
            2: return frame.kind; 3: return frame.flags;
            4: return frame.opcode[7:0]; 5: return frame.opcode[15:8];
            6: return frame.status[7:0]; 7: return frame.status[15:8];
            8: return frame.request_id[7:0]; 9: return frame.request_id[15:8];
            10: return frame.request_id[23:16]; 11: return frame.request_id[31:24];
            12: return frame.session_id[7:0]; 13: return frame.session_id[15:8];
            14: return frame.session_id[23:16]; 15: return frame.session_id[31:24];
            16: return frame.session_id[39:32]; 17: return frame.session_id[47:40];
            18: return frame.session_id[55:48]; 19: return frame.session_id[63:56];
            20: return frame.length[7:0]; 21: return frame.length[15:8];
            22: return frame.reserved[7:0]; 23: return frame.reserved[15:8];
            default: return frame.payload[{8'(index-24),3'b0}+:8];
        endcase
    endfunction
    function automatic dbg_frame_t dbg_reply(input dbg_frame_t request,input logic [15:0] status);
        dbg_frame_t response;
        logic unused_request_fields;
        unused_request_fields=^{request.version,request.kind,request.flags,request.status,request.length,request.reserved,request.payload};
        response='0; response.version=DBG_PROTOCOL_VERSION;
        response.channel=request.channel; response.kind=DBG_KIND_RESPONSE;
        response.opcode=request.opcode; response.status=status;
        response.request_id=request.request_id; response.session_id=request.session_id;
        return response;
    endfunction
    function automatic logic [DBG_MAX_PAYLOAD*8-1:0] dbg_identity(
        input logic [31:0] build_id,clock_hz,capabilities,input logic [7:0] cpu_state);
        logic [DBG_MAX_PAYLOAD*8-1:0] value;
        value='0; value[0+:8]=DBG_PROTOCOL_VERSION; value[8+:8]=DBG_SCHEMA_MINOR;
        value[16+:16]=36; value[32+:32]=build_id;
        value[64+:32]=(cpu_state==DBG_CPU_ABSENT) ? 0 : DBG_ISA_RV32I;
        value[96+:32]=clock_hz; value[128+:16]=16'(DBG_MAX_PAYLOAD);
        value[144+:16]=16'(DBG_MAX_CHUNK); value[160+:32]=capabilities;
        value[224+:8]=cpu_state; value[272+:16]=1;
        return value;
    endfunction
endpackage
"""]
    return "\n".join(out)


def c_header():
    s = SCHEMA
    out = ["/* Generated by scripts/gen_protocol.py from protocol/schema.json. Do not edit. */",
           "#ifndef DBGLINK_SCHEMA_H", "#define DBGLINK_SCHEMA_H", "", "#include <stdint.h>",
           "#include <string.h>", "",
           f"#define DBL_PROTOCOL_VERSION {s['protocol_version']}u",
           f"#define DBL_SCHEMA_MINOR {s['schema_minor']}u", ""]
    for k, v in s["limits"].items():
        out.append(f"#define DBL_{k.upper()} {v}u")
    groups = [("channels", "DBL_CH_"), ("kinds", "DBL_KIND_"), ("opcodes", "DBL_OP_"),
              ("status", "DBL_ST_"), ("frame_errors", "DBL_ERR_"), ("capabilities", "DBL_CAP_"),
              ("cpu_states", "DBL_CPU_"), ("operation_states", "DBL_OPST_"),
              ("link_states", "DBL_LINK_"), ("session_states", "DBL_SESSION_"),
              ("halt_reasons", "DBL_HALT_"), ("isa_flags", "DBL_ISA_"),
              ("status_valid_bits", "DBL_VALID_")]
    for group, prefix in groups:
        out.append("")
        bitwise = group in ("capabilities", "isa_flags", "status_valid_bits")
        for k, v in s[group].items():
            out.append(f"#define {prefix}{k} {('(1u << ' + str(v) + ')') if bitwise else str(v) + 'u'}")
    out.append(f"#define DBL_FRAME_ERROR_COUNT {len(s['frame_errors'])}u")
    out += ["", "static const char *const dbl_frame_error_names[] = {"]
    out += [f'    "{k}",' for k in s["frame_errors"]]
    out += ["};"]
    for name, fields in s["payloads"].items():
        lname = name.lower()
        size = sum(C_SIZE[t] for _, t in fields)
        out += ["", f"#define DBL_{name}_BYTES {size}u", "typedef struct {"]
        out += [f"    {C_TYPE[t]} {f};" for f, t in fields]
        out += [f"}} dbl_{lname}_t;", "",
                f"static inline int dbl_unpack_{lname}(const uint8_t *p, uint16_t n, dbl_{lname}_t *o)",
                "{", f"    if (n != DBL_{name}_BYTES) return -1;"]
        off = 0
        for f, t in fields:
            w = C_SIZE[t]
            parts = " | ".join(f"(({C_TYPE[t]})p[{off + i}] << {8 * i})" for i in range(w))
            out.append(f"    o->{f} = {parts};")
            off += w
        out += ["    return 0;", "}"]
    out += ["", "#endif", ""]
    return "\n".join(out)


def fmt_frame(f):
    return (f"{f.version} {f.channel} {f.kind} {f.flags} {f.opcode:04x} {f.status:04x} "
            f"{f.request_id:08x} {f.session_id:016x} {f.payload.hex() or '-'}")


def frames_vectors():
    rng = random.Random(0x7232)
    lines = ["# Debug protocol v1 framing vectors. Generated by scripts/gen_protocol.py.",
             "# ok  <name> <ver> <chan> <kind> <flags> <opcode> <status> <request_id> <session_id> <payload|-> <wire>",
             "# err <name> <ERROR> <encoded-without-delimiter>",
             "# crc <name> <data|-> <crc32>",
             "# cobs <name> <raw|-> <encoded-without-delimiter>",
             "# Hex is lowercase; multibyte header values are shown big-endian here and sent little-endian."]
    for name, data in (("check", b"123456789"), ("empty", b""), ("zero", b"\0"),
                       ("ff4", b"\xff" * 4), ("all256", bytes(range(256)))):
        lines.append(f"crc {name} {data.hex() or '-'} {crc32(data):08x}")
    for name, data in (("zeros4", b"\0" * 4), ("doc_example", bytes.fromhex("11220033")),
                       ("run254", bytes(range(1, 255))), ("run255", bytes(range(1, 256))),
                       ("all256", bytes(range(256))), ("ones284", b"\1" * 284)):
        lines.append(f"cobs {name} {data.hex() or '-'} {cobs_encode(data).hex()}")

    good = [
        ("hello_discovery", Frame(0, 0, OPCODE.HELLO)),
        ("hello_claim", Frame(0, 0, OPCODE.HELLO, 0, 1, 0x0123456789ABCDEF)),
        ("ping_empty", Frame(0, 0, OPCODE.PING, 0, 2, 0x0123456789ABCDEF)),
        ("ping_zeros", Frame(0, 0, OPCODE.PING, 0, 3, 0x0123456789ABCDEF, b"\0" * 32)),
        ("status_resp_busy", Frame(0, 1, OPCODE.HELLO, 0x0105, 1, 0x00FF00FF00FF00FF)),
        ("event_ch2", Frame(2, 2, OPCODE.STATUS, 0, 0, 0, b"\x01\x02")),
        ("console_ch1", Frame(1, 0, OPCODE.CONSOLE_WRITE, 0, 0xFFFFFFFF, 0xFFFFFFFFFFFFFFFF, b"hi\n")),
        ("all_byte_values", Frame(0, 1, OPCODE.MEM_READ, 0, 0x80000000, 1, bytes(range(256)))),
        ("max_payload_ff", Frame(0, 1, OPCODE.TRACE_READ, 0, 9, 2, b"\xff" * 256)),
        ("max_payload_00", Frame(0, 1, OPCODE.TRACE_READ, 0, 10, 2, b"\x00" * 256)),
        ("payload_254_nonzero", Frame(0, 1, OPCODE.PING, 0, 11, 3, b"\x5a" * 254)),
    ]
    for i in range(12):
        n = rng.choice((0, 1, 2, 31, 32, 200, 255, 256, rng.randrange(257)))
        payload = bytes(rng.choice((0, 0xFF, rng.randrange(256))) for _ in range(n))
        good.append((f"random{i:02d}", Frame(rng.randrange(3), rng.randrange(3),
                                            rng.randrange(0x10000), rng.randrange(0x10000),
                                            rng.getrandbits(32), rng.getrandbits(64), payload)))
    for name, f in good:
        lines.append(f"ok {name} {fmt_frame(f)} {wire_frame(f).hex()}")

    base = encode_frame(Frame(0, 0, OPCODE.PING, 0, 5, 0x1122334455667788, b"\x00abc"))

    def refix(raw, i, v):
        b = bytearray(raw)
        b[i] = v
        body = bytes(b[:-4])
        return body + struct.pack("<I", crc32(body))

    bad = [
        ("too_long_encoded", b"\x01" * 287),
        ("too_long_decoded", b"\x01" * 286),
        ("cobs_past_end", bytes.fromhex("0511223344")[:-1]),
        ("cobs_truncated_frame", cobs_encode(base)[:-1]),
        ("crc_hidden_code_swap", cobs_encode(base)[:-1] + b"\x09"),
        ("too_short_empty_block", b"\x01"),
        ("too_short_27", cobs_encode(base[:27])),
        ("bad_length_short", cobs_encode(base[:-1])),
        ("bad_length_extra", cobs_encode(base + b"\x00")),
        ("bad_length_field", cobs_encode(refix(base, 20, 3))),
        ("bad_length_over_256", cobs_encode(refix(refix(base, 20, 1), 21, 1))),
        ("bad_crc", cobs_encode(base[:-1] + bytes([base[-1] ^ 0x80]))),
        ("bad_crc_payload_bit", cobs_encode(base[:25] + bytes([base[25] ^ 1]) + base[26:])),
        ("bad_version_0", cobs_encode(refix(base, 0, 0))),
        ("bad_version_2", cobs_encode(refix(base, 0, 2))),
        ("bad_flags", cobs_encode(refix(base, 3, 0x80))),
        ("bad_reserved", cobs_encode(refix(base, 22, 1))),
        ("bad_channel", cobs_encode(refix(base, 1, 3))),
        ("bad_kind", cobs_encode(refix(base, 2, 0xFF))),
    ]
    for name, enc in bad:
        assert 0 not in enc, name
        try:
            from dbglink import decode_frame
            decode_frame(enc)
            raise AssertionError(f"{name} decoded")
        except FrameError as err:
            lines.append(f"err {name} {err.name} {enc.hex()}")
    return "\n".join(lines) + "\n"


A, B = 0xA1A2A3A4A5A6A7A8, 0xB1B2B3B4B5B6B7B8


def sessions_vectors():
    """Scenario steps: 'at <ms>', 'reset', 'send <wire>', 'expect <wire|none>'."""
    def req(op, rid, sid, payload=b"", ch=0, status=0):
        return Frame(ch, KIND.REQUEST, op, status, rid, sid, payload)

    scenarios = {
        "discovery_read_only": [req(OPCODE.HELLO, 0, 0), req(OPCODE.STATUS, 0, 0),
                                req(OPCODE.HELLO, 3, 0), req(OPCODE.HELLO, 0, A)],
        "claim_ping_status": [req(OPCODE.HELLO, 1, A), req(OPCODE.PING, 2, A, b"ping"),
                              req(OPCODE.STATUS, 3, A)],
        "lost_reply_identical_retry": [req(OPCODE.HELLO, 1, A), req(OPCODE.PING, 2, A, b"x"),
                                       req(OPCODE.PING, 2, A, b"x")],
        "same_id_different_body": [req(OPCODE.HELLO, 1, A), req(OPCODE.PING, 2, A, b"x"),
                                   req(OPCODE.PING, 2, A, b"y"), req(OPCODE.PING, 2, A, b"x")],
        "stale_and_zero_id": [req(OPCODE.HELLO, 1, A), req(OPCODE.PING, 9, A),
                              req(OPCODE.PING, 8, A), req(OPCODE.PING, 0, A)],
        "busy_second_client": [req(OPCODE.HELLO, 1, A), req(OPCODE.HELLO, 1, B),
                               req(OPCODE.PING, 2, B), req(OPCODE.HELLO, 0, 0)],
        "lease_expiry_rebind": [req(OPCODE.HELLO, 1, A), ("at", 1999), req(OPCODE.HELLO, 1, B),
                                ("at", 3998), req(OPCODE.HELLO, 1, B), req(OPCODE.PING, 2, A)],
        "reset_during_session": [req(OPCODE.HELLO, 1, A), req(OPCODE.PING, 2, A), ("reset",),
                                 req(OPCODE.PING, 2, A), req(OPCODE.HELLO, 1, A)],
        "id_wrap": [req(OPCODE.HELLO, 0xFFFFFFFE, A), req(OPCODE.PING, 0xFFFFFFFF, A),
                    req(OPCODE.PING, 1, A)],
        "unsupported_and_bad_args": [req(OPCODE.HELLO, 1, A), req(OPCODE.STEP, 2, A),
                                     req(OPCODE.PING, 3, A, b"\0" * 33),
                                     req(OPCODE.PING, 4, A, ch=CHANNEL.CONSOLE),
                                     req(OPCODE.PING, 5, A, status=1),
                                     req(OPCODE.STATUS, 6, A, b"\1"),
                                     req(0x7777, 7, A), req(OPCODE.STEP, 2, A)],
        "response_sent_to_device": [Frame(0, KIND.RESPONSE, OPCODE.PING, 0, 1, A),
                                    Frame(2, KIND.EVENT, OPCODE.PING, 0, 0, 0)],
    }
    lines = ["# Debug protocol v1 device session vectors. Generated by scripts/gen_protocol.py",
             "# from host/dbglink/device.py; expectations are hand-checked in host/tests/test_device.py.",
             "# Each scenario starts from a freshly reset device at time 0 ms.",
             "# scenario <name> | at <ms> | reset | send <wire> | expect <wire|none>",
             "# Device identity: build_id 0x54320001, clock 62500000 Hz, CPU present."]
    for name, steps in scenarios.items():
        dev, now = DebugDevice(), 0
        lines.append(f"scenario {name}")
        for step in steps:
            if isinstance(step, tuple):
                if step[0] == "at":
                    now = step[1]
                    lines.append(f"at {now}")
                else:
                    dev.reset()
                    lines.append("reset")
                continue
            lines.append(f"send {wire_frame(step).hex()}")
            reply = dev.handle(step, now)
            lines.append(f"expect {wire_frame(reply).hex() if reply else 'none'}")
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    stale = []
    for path, text in ((HEADER_OUT, c_header()), (RTL_OUT, sv_package()), (FRAMES_OUT, frames_vectors()),
                       (SESSIONS_OUT, sessions_vectors())):
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(path.relative_to(REPO))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(REPO)}")
    if stale:
        print("out of date (run scripts/gen_protocol.py):", *stale, sep="\n  ")
        return 1
    if args.check:
        print("protocol files up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main())
